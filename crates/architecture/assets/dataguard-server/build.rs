//! Discovers what the server binds: every `aggregate.json` (contract I)
//! and every `data-capability.json` (contract F) of the repository, and the
//! registry of persisted queries (contract C). Writes `registry.rs` in
//! `OUT_DIR`, which `main.rs` includes: the server starts with every
//! manifest the checkout holds, and a DataCapability added in parallel is
//! registered by its folder alone — plus its dependency line, which merges
//! on its own.

use std::env;
use std::fs;
use std::path::{Path, PathBuf};

fn main() {
    let root = Path::new(env!("CARGO_MANIFEST_DIR"))
        .ancestors()
        .nth(3)
        .expect("crates/dataguard/server sits three levels under the root")
        .to_path_buf();
    println!("cargo:rerun-if-changed={}", root.join("crates").display());
    println!("cargo:rerun-if-changed={}", root.join("queries").display());
    let aggregates = found(&root.join("crates"), "aggregate.json");
    let manifests = found(&root.join("crates"), "data-capability.json");
    let registry = root.join("queries/registry.json");
    let mut out = String::from("/// Generated by build.rs: what the checkout holds.\n");
    out.push_str("pub const AGGREGATES: &[&str] = &[\n");
    for path in &aggregates {
        out.push_str(&format!("    include_str!({:?}),\n", path.display().to_string()));
    }
    out.push_str("];\npub const DATA_CAPABILITIES: &[&str] = &[\n");
    for path in &manifests {
        out.push_str(&format!("    include_str!({:?}),\n", path.display().to_string()));
    }
    out.push_str("];\n");
    if registry.is_file() {
        out.push_str(&format!(
            "pub const REGISTRY: &str = include_str!({:?});\n",
            registry.display().to_string()
        ));
    } else {
        out.push_str("pub const REGISTRY: &str = \"{\\\"queries\\\":[]}\";\n");
    }
    let dest = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR")).join("registry.rs");
    fs::write(dest, out).expect("write registry.rs");
}

/// Every file named `name` under `dir`, sorted, skipping `target/`.
fn found(dir: &Path, name: &str) -> Vec<PathBuf> {
    let mut out = Vec::new();
    let Ok(entries) = fs::read_dir(dir) else {
        return out;
    };
    for entry in entries.flatten() {
        let path = entry.path();
        if path.is_dir() {
            if path.file_name().is_some_and(|n| n == "target") {
                continue;
            }
            out.extend(found(&path, name));
        } else if path.file_name().is_some_and(|n| n == name) {
            out.push(path);
        }
    }
    out.sort();
    out
}
